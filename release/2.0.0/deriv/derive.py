#!/usr/bin/env python3
"""Derives the deontic closure, Hohfeldian positions, prevalence orderings and
weak permissions of a NORMA ABox.

The annotation graph is never modified: everything generated goes to a
separate, regenerable graph, together with a normad:DerivationActivity that
states the non-monotonic assumptions the conclusions depend on.

  python deriv/derive.py <abox.ttl> [<cases.ttl> ...] -o out.ttl
"""
from __future__ import annotations

import argparse
import hashlib
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import OWL, PROV, RDF, RDFS, XSD

sys.path.insert(0, str(Path(__file__).resolve().parent))
from prevalence import APPLICABLE, DEFEATED, UNDECIDED, grounded, strata

NORMA = Namespace("https://w3id.org/def/norma-o#")
NORMAD = Namespace("https://w3id.org/def/norma-o/deriv#")
# The ontology folder is the one that contains deriv/, so this rule set works
# unchanged wherever the release folder is placed. NORMA_ONTOLOGY_DIR points it
# at another copy.
ONTO = Path(os.environ.get("NORMA_ONTOLOGY_DIR")
            or Path(__file__).resolve().parent.parent)
TBOX = ONTO / "norma-ontology-v2.ttl"
MODULE = ONTO / "norma-o-deriv.ttl"
RULES = Path(__file__).resolve().parent / "rules"
RULE_SET_VERSION = "norma-derivation/1.0"

STAGE12 = ["01-action-negation.rq", "01b-negation-symmetry.rq", "02a-closure-obligation.rq", "02b-closure-prohibition.rq",
           "02c-closure-permission.rq", "02d-closure-facultative.rq",
           "02e-closure-recommendation.rq", "02f-closure-negative-recommendation.rq"]


SWRL = Namespace("http://www.w3.org/2003/11/swrl#")


def _load_input(work: Graph, path: Path) -> None:
    """Loads a file, deciding by its CONTENT rather than its extension.

    Every .owl or .rdf file used to be treated as a rule artefact, so an ABox
    serialised in RDF/XML silently lost everything except activation. Now the
    graph is checked for SWRL atoms: if it has them it is a rule artefact and
    only activation is extracted; otherwise it is an ABox and loaded whole.
    """
    fmt = "turtle" if path.suffix.lower() in (".ttl", ".n3", ".nt", ".turtle") else "xml"
    g = Graph()
    g.parse(path, format=fmt)
    if next(g.subjects(SWRL.propertyPredicate, None), None) is not None:
        n = _load_swrl_activations(work, g)
        print(f"[norma] {path.name}: rule artefact, {n} activation(s)")
    else:
        work += g


def _load_swrl_activations(work: Graph, s: Graph) -> int:
    """Brings norma:activatesNorm in from the SWRL artefact.

    An ABox generated by an annotation toolkit may declare TriggerEvents without
    activatesNorm: that link then lives in the HEADS of the SWRL rules, because
    activation is conditional. Without reading it from there, the set of
    activations is empty for every generated pack, normad:NotActivated can
    never fire, and an untriggered norm looks applicable merely because nothing
    defeats it.

    ONLY activatesNorm is extracted. The rule bodies use predicates from the
    rules: namespace, and importing them would assert as unconditional what the
    rule makes conditional. activatesNorm is different: it says that THIS
    trigger activates that norm, not that the norm is active; whether it fires
    in a concrete case is decided by norma:holdsTrigger.
    """
    n = 0
    for atom in s.subjects(SWRL.propertyPredicate, NORMA.activatesNorm):
        a1 = s.value(atom, SWRL.argument1)
        a2 = s.value(atom, SWRL.argument2)
        if a1 is not None and a2 is not None:
            work.add((a1, NORMA.activatesNorm, a2))
            n += 1
    return n


def run_rule(work: Graph, name: str, **bindings) -> Graph:
    q = (RULES / name).read_text(encoding="utf-8")
    out = Graph()
    for triple in work.query(q, initBindings=bindings or None):
        out.add(triple)
    return out


def derive(abox_path: Path, timestamp: bool, base: str | None):
    work = Graph()
    work.parse(TBOX, format="turtle")
    work.parse(MODULE, format="turtle")
    before = len(work)
    for p in ([abox_path] if isinstance(abox_path, Path) else list(abox_path)):
        _load_input(work, p)
    abox_only = len(work) - before

    onto = next((s for s in work.subjects(RDF.type, OWL.Ontology)
                 if "def/norma-o" not in str(s)), None)
    base = base or (f"{onto}/derived#" if onto else "https://w3id.org/norma-abox/derived#")

    derived = Graph()
    report = {}

    # ── stages 1 and 2: action negation and deontic closure ──────────────
    for name in STAGE12:
        res = run_rule(work, name)
        report[name] = len(res)
        derived += res
        work += res              # the closure needs the negations, and
                                 # stage 3 needs the closure

    # ── stage 3: weak permission, under the chosen reading of the case ───
    # Explicit negation as failure: candidates minus blocked. It is done here
    # rather than inside a CONSTRUCT so that each query stays flat and readable.
    inputs = [abox_path] if isinstance(abox_path, Path) else list(abox_path)
    payload = hashlib.sha256(
        ("".join(p.read_text(encoding="utf-8") for p in inputs) + RULE_SET_VERSION).encode()
    ).hexdigest()[:12]
    activity = URIRef(f"{base}derivation_{payload}")

    # ── stage 3a: defeat digraph, validity, ladder and labelling ─────────
    EX, CF, TM = NORMA.ExceptionDefeater, NORMA.ConflictDefeater, NORMA.TemporalDefeater
    ln = lambda u: str(u).rsplit("#", 1)[-1].rsplit("/", 1)[-1]

    # One defeater per node, with its gates and principles. The gates of ONE
    # defeater are read conjunctively and alternative defeaters disjunctively,
    # which is why the gates of the same edge cannot be merged.
    dfrs: dict = {}
    for dfr, kind, a, b, gate, principle in work.query(
            (RULES / "03a-defeat-edges.rq").read_text(encoding="utf-8")):
        d = dfrs.setdefault(dfr, {"a": a, "b": b, "kind": None,
                                  "gates": set(), "principles": set()})
        if kind in (EX, CF, TM):            # the most specific kind wins
            d["kind"] = kind
        if gate is not None:
            d["gates"].add(gate)
        if principle is not None:
            d["principles"].add(principle)
    for a, b, kind in work.query(
            (RULES / "03a-defeat-shortcuts.rq").read_text(encoding="utf-8")):
        dfrs[(a, b, kind)] = {"a": a, "b": b, "kind": kind,
                              "gates": set(), "principles": set()}
    report["03a-defeat-edges.rq"] = len(dfrs)

    # Triggers that activate each norm. Several are read DISJUNCTIVELY; a norm
    # with none is unconditional and is never NotActivated.
    trig: dict = {}
    for te, n in work.subject_objects(NORMA.activatesNorm):
        trig.setdefault(n, set()).add(te)

    # A norm is any instance of norma:NormativeContent, identified by its TYPE
    # and not by carrying a norma:deonticId. Identifying norms by the literal
    # left any norm without one out of the evaluation, and a prohibition with
    # no status blocks nothing: FALSE weak permissions were generated over
    # explicitly forbidden actions. The deonticId is an annotation shortcut,
    # not the identity of the norm.
    norms = {n for n, in work.query("""
        PREFIX norma: <https://w3id.org/def/norma-o#>
        PREFIX rdfs:  <http://www.w3.org/2000/01/rdf-schema#>
        SELECT DISTINCT ?n WHERE {
          ?n a ?c . ?c rdfs:subClassOf* norma:NormativeContent .
        }""")}
    norms |= {d["a"] for d in dfrs.values()} | {d["b"] for d in dfrs.values()}
    strict = set(work.subjects(NORMA.hasNormStrength, NORMA.Strict))

    def applicable(d, held):
        """held None = projection without gates (the static ladder)."""
        return held is None or d["gates"] <= held

    def operative(n, held):
        """A norm not triggered by the case is not operative, so it DOES NOT DEFEAT.

        The condition of an exception may be annotated in two places: on the
        activation of the excepting norm and on the defeater's appliesWhen
        gate. BOTH are required, conjunctively: the gate says when the defeat
        relation applies, and the activation says whether the defeating norm
        exists in the case at all. So the annotator may put the condition in
        either place and get the right answer, and if the two conditions
        differ the result is their conjunction, which is the conservative
        reading.
        """
        return held is None or n not in trig or bool(trig[n] & held)

    def edge_set(kinds, held):
        # Edges against a Strict norm are excluded from the whole digraph, not
        # only from the labelling: keeping them would give that norm a level
        # asserting that something prevails over it, contradicting its status.
        #
        # The edge is filtered HERE and not when reporting: the attack graph
        # must be clean before the fixpoint. If only the displayed status were
        # overwritten, an untriggered exception would still defeat its rule.
        # An invalid attacker is already filtered by the node set, `valid`,
        # because _attackers drops edges with an endpoint outside it.
        return {(d["a"], d["b"]) for d in dfrs.values()
                if d["kind"] in kinds and applicable(d, held)
                and not (d["b"] in strict and kinds != {TM})
                and operative(d["a"], held)}

    # Validity BEFORE the case graph, as norma:TemporalDefeater prescribes:
    # derogation concerns membership of the system, not applicability.
    status_bad = (set(work.subjects(NORMA.hasNormStatus, NORMA.Superseded))
                  | set(work.subjects(NORMA.hasNormStatus, NORMA.NotYetInForce))
                  | set(work.subjects(NORMA.supersededBy, None)))
    # Temporal defeat is applied FLAT, not under grounded semantics, and the
    # difference is substantive: repealing the repealing norm does not restore
    # the repealed one. A norm that has left the system does not come back,
    # whereas a norm merely disapplied by an exception is reinstated when the
    # exception falls. Under grounded semantics, a chain w1 repeals w2 repeals
    # w3 would revive w3, which is false by default in law. The repealing norm
    # must itself be in force, though: a norm not yet in force repeals nothing.
    invalid = status_bad | {d["b"] for d in dfrs.values()
                            if d["kind"] == TM and d["a"] not in status_bad}
    valid = sorted(norms - invalid, key=str)

    # Defeating a Strict norm is an annotator contradiction, not a fact.
    unsound_facts: list = []
    unsound_roles: list = []
    facts_chained: set = set()
    void_attacks = sorted({(d["a"], d["b"]) for d in dfrs.values()
                           if d["b"] in strict and d["kind"] in (EX, CF)}, key=str)

    def role_players(case):
        """Parties the case places in each role: role -> {parties}."""
        out: dict = {}
        if case is None:
            return out
        for ra in work.objects(case, NORMA.holdsRoleAssignment):
            p = work.value(ra, NORMA.hasAssignedParty)
            r = work.value(ra, NORMA.hasAssignedRole)
            if p is not None and r is not None:
                out.setdefault(r, set()).add(p)
        return out

    def label_at(held):
        """Full labelling for a given set of triggers that hold."""
        g = grounded(valid, edge_set({EX, CF}, held), strict)
        out = {}
        for n in norms:
            if n in invalid:
                out[n] = "Invalid"
            elif n in trig and not (trig[n] & held):
                out[n] = "NotActivated"
            else:
                out[n] = g[n]
        return out

    def institutional_closure(held0):
        """Alternates constitutive -> regulative until a fixpoint.

        A constitutive rule that applies ESTABLISHES a fact of the case
        (norma:establishesTrigger), and that fact may activate regulative
        norms. Evaluating once over the brute facts skips that rung: an
        obligation conditioned on being high-risk is not defeated when the
        classification that makes the system high-risk is defeated.
        The set of facts only grows, so the alternation terminates.
        """
        held = set(held0)
        while True:
            lab = label_at(held)
            grown = set(held)
            for n, st in lab.items():
                if st == APPLICABLE:
                    grown |= set(work.objects(n, NORMA.establishesTrigger))
            if grown == held:
                return held, lab
            held = grown

    def emit_ordering(case, held):
        plays = role_players(case)
        derived_facts: set = set()
        if case is not None:
            closed, _ = institutional_closure(held)
            derived_facts = closed - set(held)
            facts_chained.update(derived_facts)
            held = closed
        app = edge_set({EX, CF}, held)
        # Levels over the CONDENSATION: the acyclic descendants of a cycle get
        # a rung, and the norms of one cycle share their component's rung.
        # Kahn alone would leave them without a level.
        levels, cyc, _cyclic = strata(valid, app)
        lab = None
        if case is not None:
            # Precedence of the five statuses: validity first, which is
            # membership of the system; then activation, because asking whether
            # an untriggered norm is defeated makes no sense; and only for
            # valid, activated norms, the grounded labelling.
            lab = label_at(held)
            # An institutional fact whose rule ended up NOT applying stays in
            # the case: the alternation grows and never undoes. It is reported,
            # because a conclusion resting on it is suspect.
            for te in sorted(derived_facts, key=str):
                if not any(lab.get(n) == APPLICABLE
                           for n in work.subjects(NORMA.establishesTrigger, te)):
                    unsound_facts.append((ln(case), ln(te)))
            # A role assignment is asserted and never retracted, so it may sit in
            # a case citing a rule that does not apply there. Nothing is
            # derived: a warning is issued, as with institutional facts.
            for ra in sorted(work.objects(case, NORMA.holdsRoleAssignment), key=str):
                for rule in sorted(work.objects(ra, NORMA.assignedUnderRule), key=str):
                    st = lab.get(rule)
                    if st is not None and st != APPLICABLE:
                        unsound_roles.append((ln(case), ln(ra), ln(rule), st))
        oid = URIRef(base + ("ordering_" + ln(case) if case is not None
                             else "ordering_static"))
        derived.add((oid, RDF.type, NORMAD.PrevalenceOrdering))
        derived.add((oid, PROV.wasGeneratedBy, activity))
        derived.add((oid, NORMAD.isAcyclic, Literal(not cyc, datatype=XSD.boolean)))
        derived.add((oid, NORMAD.stratumCount,
                     Literal(max(levels.values()) + 1 if levels else 0,
                             datatype=XSD.nonNegativeInteger)))
        if case is not None:
            derived.add((oid, NORMAD.forFactPattern, case))
        for n in (sorted(norms, key=str) if case is not None else valid):
            ev = URIRef(f"{oid}_eval_{ln(n)}")
            derived.add((ev, RDF.type, NORMAD.NormEvaluation))
            derived.add((ev, NORMAD.evaluatedNorm, n))
            derived.add((ev, NORMAD.inOrdering, oid))
            if n in levels:      # absent on a cycle or downstream of one
                derived.add((ev, NORMAD.prevalenceLevel,
                             Literal(levels[n], datatype=XSD.nonNegativeInteger)))
            if lab is not None:  # the static ladder orders, it does not decide cases
                derived.add((ev, NORMAD.hasApplicabilityStatus, NORMAD[lab[n]]))
                # Which concrete PARTY the norm reaches in this case. A norm
                # addressed to a role reaches whoever the case places in that
                # role; one addressed to a party reaches that party. Reach and
                # applicability are distinct questions: reach is emitted
                # whatever the status, and the consumer joins the two.
                for ag in work.objects(n, NORMA.hasLegalAgent):
                    if (ag, RDF.type, NORMA.LegalParty) in work:
                        derived.add((ev, NORMAD.reachesParty, ag))
                    for party in plays.get(ag, ()):
                        derived.add((ev, NORMAD.reachesParty, party))
        for comp in cyc:
            cid = URIRef(f"{oid}_cycle_" + "_".join(ln(n) for n in comp))
            derived.add((cid, RDF.type, NORMAD.PrevalenceCycle))
            derived.add((oid, NORMAD.inCycle, cid))
            for n in comp:
                derived.add((cid, NORMAD.involvesNorm, n))
            inner = [d for d in dfrs.values() if d["a"] in comp and d["b"] in comp
                     and applicable(d, held)]
            prin = {p for d in inner for p in d["principles"]}
            for p in sorted(prin, key=str):
                derived.add((cid, NORMAD.citesCompetingPrinciple, p))
            if inner and all(d["kind"] == CF for d in inner) and len(prin) >= 2:
                k = NORMAD.SecondDegreeConflict      # Bobbio: unordered criteria
            elif inner and all(d["kind"] == CF for d in inner) and len(prin) == 1:
                k = NORMAD.AnnotationContradiction   # one principle cannot support both
            else:
                k = NORMAD.IrresolubleAntinomy
            derived.add((cid, NORMAD.hasCycleKind, k))
        return lab, cyc

    _, static_cyc = emit_ordering(None, None)
    case_lab = {}
    for C in sorted(work.subjects(RDF.type, NORMA.FactPattern), key=str):
        held = set(work.objects(C, NORMA.holdsTrigger))
        case_lab[C] = emit_ordering(C, held)[0]
    report["03a-orderings"] = 1 + len(case_lab)

    # ── stage 3b/3c: weak permission, over the grounded labelling ────────
    cands = {tuple(r) for r in work.query(
        (RULES / "03b-wp-candidates.rq").read_text(encoding="utf-8"))}
    rows = {tuple(r) for r in work.query(
        (RULES / "03c-wp-blocked.rq").read_text(encoding="utf-8"))}
    # An UNDECIDED prohibition also blocks: while its fate is not settled, it
    # cannot be asserted that the action is not forbidden. Invalid and
    # NotActivated do not block, which is exactly what those two statuses are
    # there to distinguish.
    blocked = {(A, y, C) for A, y, C, b in rows
               if case_lab.get(C, {}).get(b) in (APPLICABLE, UNDECIDED)}
    report["03b-wp-candidates.rq"] = len(cands)
    report["03c-wp-blocked.rq"] = len(blocked)
    for A, y, C in sorted(cands - blocked, key=lambda t: tuple(str(x) for x in t)):
        wp = URIRef(base + "wp_" + hashlib.md5(
            (str(A) + str(y) + str(C)).encode()).hexdigest())
        derived.add((wp, RDF.type, NORMA.WeakPermission))
        derived.add((wp, NORMA.aboutAction, y))
        derived.add((wp, NORMA.forAgent, A))
        derived.add((wp, NORMA.inFactPattern, C))
        derived.add((wp, PROV.wasGeneratedBy, activity))

    # ── stage 4: Hohfeldian positions from the closure ───────────────────
    for name in ("04a-position-duty.rq", "04b-position-privilege.rq",
                 "04c-jural-opposite.rq", "04d-jural-opposite-correlatives.rq"):
        res = run_rule(work, name)
        if name.startswith("04c"):
            # opposition is symmetric: the rule emits one direction
            for su, _, o in list(res):
                res.add((o, NORMA.isJuralOppositeOf, su))
            report[name] = len(res)
        elif name.startswith("04d"):
            for su, _, o in list(res):
                res.add((o, NORMA.isJuralOppositeOf, su))
            report[name] = len(res)
        else:
            report[name] = len(res)
        derived += res
        work += res              # 04c needs the positions, 04d the opposition
    # Every norm with a regulated action, not only those conferring a duty: a
    # privilege without a counterparty loses its no-right just as a duty loses
    # its claim, and it also enters the comparisons of 04c and 05a-c.
    no_cp = sorted((n for n in norms
                    if list(work.objects(n, NORMA.hasLegalAction))
                    and not list(work.objects(n, NORMA.hasCounterparty))), key=str)
    # The permissive reading of the counterparty is applied by 04c and 05a-c,
    # which range over EVERY norm with a regulated action, not only those
    # entailing an obligation: a permission without a counterparty enters the
    # comparison just the same. If any lacks a counterparty, the derived graph
    # contains relations that depend on the assumption, and it must be declared.
    silent_cp = bool(no_cp)

    # ── stage 5: norm-to-norm relations, by joining over the closure ─────
    pairs = {
        "05a-deontic-equivalence.rq":  (NORMA.isDeonticallyEquivalentTo, True),
        "05b-deontic-contradiction.rq": (NORMA.deonticallyContradicts, True),
        "05c-deontic-contrariety.rq":   (NORMA.deonticallyConflictsWith, True),
    }
    for name, (prop, symmetric) in pairs.items():
        rows = {(r[0], r[1]) for r in work.query((RULES / name).read_text(encoding="utf-8"))}
        emitted = len(derived)
        for n1, n2 in rows:
            derived.add((n1, prop, n2))
            if symmetric:          # all three are symmetric: both directions are materialised
                derived.add((n2, prop, n1))
            if prop == NORMA.deonticallyContradicts:
                # the superproperty is materialised too, so that a conflict
                # query over the derived graph needs no reasoner
                derived.add((n1, NORMA.deonticallyConflictsWith, n2))
                derived.add((n2, NORMA.deonticallyConflictsWith, n1))
        report[name] = len(derived) - emitted

    # ── provenance and assumptions ───────────────────────────────────────
    derived.add((activity, RDF.type, NORMAD.DerivationActivity))
    derived.add((activity, RDF.type, PROV.Activity))
    derived.add((activity, NORMAD.ruleSetVersion, Literal(RULE_SET_VERSION)))
    derived.add((activity, NORMAD.derivedGraph, Literal(base.rstrip("#"), datatype=XSD.anyURI)))
    for p in inputs:
        derived.add((activity, PROV.used, URIRef(p.resolve().as_uri())))
    derived.add((activity, RDFS.label,
                 Literal("Deontic closure and per-case weak permissions", lang="en")))
    assumptions = [NORMAD.ClosedGraph, NORMAD.ClosedCaseDescription,
                   NORMAD.DefeatConsidered, NORMAD.GroundedSemantics]
    if list(work.subject_objects(NORMA.establishesTrigger)):
        assumptions.append(NORMAD.InstitutionalFactsChained)
    if silent_cp:
        assumptions.append(NORMAD.OpenCounterparty)
    for a in assumptions:
        derived.add((activity, NORMAD.computedUnderAssumption, a))
    if timestamp:
        derived.add((activity, PROV.startedAtTime,
                     Literal(datetime.now(timezone.utc).isoformat(), datatype=XSD.dateTime)))

    # ── norms left outside the closure ───────────────────────────────────
    # By TYPE, like `norms`: identifying by deonticId left a norm without that
    # literal out of the warning, which is the same bug fixed above.
    outside = [n for n in norms
               if not list(work.objects(n, NORMA.hasLegalAction))
               and (n, RDF.type, NORMA.ConstitutiveRule) not in work]
    return (derived, report, abox_only, outside, activity, base, no_cp,
            invalid, static_cyc, void_attacks, unsound_facts, facts_chained,
            unsound_roles)


def main() -> None:
    p = argparse.ArgumentParser(description="NORMA deontic closure and weak permission generator")
    p.add_argument("abox", nargs="+",
                   help="ABox, SWRL artefact (activatesNorm is taken from it) "
                        "and case files, in any order")
    p.add_argument("-o", "--out", default=None, help="output Turtle file (default: <abox>.derived.ttl)")
    p.add_argument("--timestamp", action="store_true",
                   help="include prov:startedAtTime; breaks byte-for-byte idempotence")
    p.add_argument("--base", default=None, help="base IRI for the derived individuals")
    a = p.parse_args()

    aboxes = [Path(x) for x in a.abox]
    for x in aboxes:
        if not x.exists():
            sys.exit(f"[!] not found: {x}")
    abox = aboxes[0]
    (derived, report, abox_only, outside, activity, base, no_cp,
     invalid, static_cyc, void_attacks, unsound_facts,
     facts_chained, unsound_roles) = derive(aboxes, a.timestamp, a.base)

    out = Path(a.out) if a.out else abox.with_suffix(".derived.ttl")
    derived.bind("norma", NORMA); derived.bind("normad", NORMAD); derived.bind("prov", PROV)
    out.write_text(derived.serialize(format="turtle"), encoding="utf-8")
    # Sorted N-Triples: byte-for-byte comparison for the idempotence tests
    nt = sorted(derived.serialize(format="nt").splitlines())
    out.with_suffix(".nt").write_text("\n".join(nt) + "\n", encoding="utf-8")

    print(f"ABox: {abox}  ({abox_only} triples)")
    print(f"rule set: {RULE_SET_VERSION}   weak permission: per case, with defeat")
    for name, n in report.items():
        print(f"  {name:38s} {n:4d} triples")
    print(f"TOTAL derived: {len(derived)} triples -> {out}")
    print(f"  weak permissions: {len(set(derived.subjects(RDF.type, NORMA.WeakPermission)))}")
    contra = {frozenset(p) for p in derived.subject_objects(NORMA.deonticallyContradicts)}
    confl = {frozenset(p) for p in derived.subject_objects(NORMA.deonticallyConflictsWith)}
    equiv = {frozenset(p) for p in derived.subject_objects(NORMA.isDeonticallyEquivalentTo)}
    for lab, pairs in (("equivalences", equiv), ("contradictions", contra),
                       ("contraries", confl - contra)):
        if pairs: print(f"  {lab}: {len(pairs)} pair(s)")
    opp = {frozenset(p) for p in derived.subject_objects(NORMA.isJuralOppositeOf)}
    if opp: print(f"  jural opposites: {len(opp)} pair(s)")
    for cls in ("Duty", "Claim", "Privilege", "NoRight"):
        k = len(set(derived.subjects(RDF.type, NORMA[cls])))
        if k: print(f"  {cls} positions: {k}")
    # ── prevalence ladder ────────────────────────────────────────────────
    ln = lambda u: str(u).rsplit("#", 1)[-1].rsplit("/", 1)[-1]
    stat = next((o for o in derived.subjects(RDF.type, NORMAD.PrevalenceOrdering)
                 if not list(derived.objects(o, NORMAD.forFactPattern))), None)
    if stat is not None:
        lv = {}
        for ev in derived.subjects(NORMAD.inOrdering, stat):
            n = derived.value(ev, NORMAD.evaluatedNorm)
            l = derived.value(ev, NORMAD.prevalenceLevel)
            lv.setdefault(int(l) if l is not None else -1, []).append(ln(n))
        print(f"  static ladder: {derived.value(stat, NORMAD.stratumCount)} stratum(s), "
              f"acyclic={derived.value(stat, NORMAD.isAcyclic)}")
        for k in sorted(lv):
            tag = "level " + str(k) if k >= 0 else "no level (cycle)"
            print(f"    {tag:18} {', '.join(sorted(lv[k]))}")
    for C in sorted(derived.objects(None, NORMAD.forFactPattern), key=str):
        o = next(derived.subjects(NORMAD.forFactPattern, C))
        by = {}
        for ev in derived.subjects(NORMAD.inOrdering, o):
            st = derived.value(ev, NORMAD.hasApplicabilityStatus)
            by.setdefault(ln(st), []).append(ln(derived.value(ev, NORMAD.evaluatedNorm)))
        parts = [f"{k} {len(v)}" for k, v in sorted(by.items())]
        reach = {}
        for ev in derived.subjects(NORMAD.inOrdering, o):
            for p in derived.objects(ev, NORMAD.reachesParty):
                reach.setdefault(ln(p), []).append(ln(derived.value(ev, NORMAD.evaluatedNorm)))
        print(f"  case {ln(C):26} {'  '.join(parts)}")
        for p in sorted(reach):
            print(f"      reaches {p}: {', '.join(sorted(reach[p]))}")
        for k in ("Defeated", "Undecided", "NotActivated", "Invalid"):
            if by.get(k):
                print(f"      {k:14} {', '.join(sorted(by[k]))}")
    if invalid:
        print(f"[!] {len(invalid)} norm(s) outside the system (repealed or not in force): "
              f"{sorted(ln(n) for n in invalid)}")
    # Each ordering reports its own cycles, because a cycle may exist on the
    # static ladder and not in a case; the report groups them.
    seen_cyc = set()
    for cid in sorted(derived.subjects(RDF.type, NORMAD.PrevalenceCycle), key=str):
        mem = tuple(sorted(ln(n) for n in derived.objects(cid, NORMAD.involvesNorm)))
        kind = ln(derived.value(cid, NORMAD.hasCycleKind))
        if (mem, kind) in seen_cyc:
            continue
        seen_cyc.add((mem, kind))
        pr = sorted(ln(p) for p in derived.objects(cid, NORMAD.citesCompetingPrinciple))
        print(f"[!] CYCLE ({kind}): {', '.join(mem)}"
              + (f"  competing principles: {', '.join(pr)}" if pr else ""))
    if facts_chained:
        print(f"  chained institutional facts: {len(facts_chained)}")
    for case, ra, rule, st in unsound_roles:
        print(f"[!] in {case}: role assignment {ra} cites {rule}, which is "
              f"{st} there; the assignment was asserted and is not retracted")
    for case, te in unsound_facts:
        print(f"[!] in {case}: fact {te} stayed in the case but no rule "
              f"establishing it turned out applicable")
    if void_attacks:
        print(f"[!] {len(void_attacks)} defeat(s) against a Strict norm, without effect "
              f"(annotation contradiction): "
              f"{[f'{ln(a)}->{ln(b)}' for a, b in void_attacks]}")
    if no_cp:
        print(f"[!] {len(no_cp)} norm(s) without norma:hasCounterparty: their position has NO "
              f"materialised correlative (no counterparty is invented): {[str(n).split('#')[-1] for n in no_cp]}")
    print(f"  activity: {activity}")
    if outside:
        print(f"[!] {len(outside)} norm(s) without norma:LegalAction are left OUTSIDE the closure "
              f"(they only have the actionText shortcut): {[str(n).split('#')[-1] for n in outside]}")


